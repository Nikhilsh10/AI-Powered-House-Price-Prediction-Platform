# src/dashboard/pages/2_Analytics.py
"""Analytics page – visual insight into data and model performance.

Shows KPI cards derived from the cleaned dataset and renders several Plotly
visualizations.  Model evaluation metrics are loaded from
`models/metrics.json` (generated by the training pipeline).
"""

import streamlit as st
import os, sys
import json
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go

# Ensure root is on path for imports if needed
PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.append(PROJECT_ROOT)

# ---------------------------------------------------------------------------
# Load data and metrics
# ---------------------------------------------------------------------------
DATA_PATH = os.path.join(PROJECT_ROOT, "data", "processed", "clean_data.csv")
METRICS_PATH = os.path.join(PROJECT_ROOT, "models", "metrics.json")

@st.cache_data
def load_dataset():
    return pd.read_csv(DATA_PATH)

@st.cache_data
def load_metrics():
    if os.path.exists(METRICS_PATH):
        with open(METRICS_PATH) as f:
            return json.load(f)
    return {}

df = load_dataset()
metrics = load_metrics()

# ---------------------------------------------------------------------------
# KPI cards (styled with glass‑card)
# ---------------------------------------------------------------------------
st.title("📊 Analytics & Model Performance")
st.markdown("---")

col1, col2, col3, col4 = st.columns(4)
with col1:
    total_props = len(df)
    st.markdown(f"<div class='glass-card'><h4>Total Properties</h4><p>{total_props}</p></div>", unsafe_allow_html=True)
with col2:
    avg_price = df["price"].mean() if "price" in df.columns else None
    st.markdown(f"<div class='glass-card'><h4>Average Price</h4><p>{avg_price:.2f} L</p></div>", unsafe_allow_html=True)
with col3:
    median_price = df["price"].median() if "price" in df.columns else None
    st.markdown(f"<div class='glass-card'><h4>Median Price</h4><p>{median_price:.2f} L</p></div>", unsafe_allow_html=True)
with col4:
    locations = df["location"].nunique() if "location" in df.columns else None
    st.markdown(f"<div class='glass-card'><h4>Locations Covered</h4><p>{locations}</p></div>", unsafe_allow_html=True)

st.markdown("---")
# ---------------------------------------------------------------------------
# Visualizations
# ---------------------------------------------------------------------------
# 1. Price Distribution
if "price" in df.columns:
    fig_price = px.histogram(df, x="price", nbins=30, title="Price Distribution")
    st.plotly_chart(fig_price, use_container_width=True)

# 2. Top Locations by average price (top 10)
if "location" in df.columns and "price" in df.columns:
    top_loc = (
        df.groupby("location")["price"]
        .mean()
        .nlargest(10)
        .reset_index()
        .rename(columns={"price": "avg_price"})
    )
    fig_top = px.bar(top_loc, x="location", y="avg_price", title="Top 10 Locations by Avg Price")
    st.plotly_chart(fig_top, use_container_width=True)

# 3. Area vs Price scatter (if area column exists)
area_col = next((c for c in ["size", "total_sqft", "area"] if c in df.columns), None)
if area_col and "price" in df.columns:
    fig_scatter = px.scatter(df, x=area_col, y="price", trendline="ols", title=f"{area_col.capitalize()} vs Price")
    st.plotly_chart(fig_scatter, use_container_width=True)

# 4. Correlation matrix heatmap (numeric columns only)
numeric_df = df.select_dtypes(include="number")
if not numeric_df.empty:
    corr = numeric_df.corr()
    fig_corr = go.Figure(data=go.Heatmap(z=corr.values, x=corr.columns, y=corr.index, colorscale="Viridis"))
    fig_corr.update_layout(title="Correlation Matrix")
    st.plotly_chart(fig_corr, use_container_width=True)

st.markdown("---")
# ---------------------------------------------------------------------------
# Model Comparison Table
# ---------------------------------------------------------------------------
st.subheader("Model Comparison")
if metrics:
    # Build DataFrame for pretty display
    rows = []
    for model_name, vals in metrics.items():
        if model_name == "best_model":
            continue
        rows.append({
            "Model": model_name.title(),
            "R²": f"{vals.get('r2', 0):.3f}",
            "MAE": f"{vals.get('mae', 0):.2f}",
            "RMSE": f"{vals.get('rmse', 0):.2f}",
        })
    comp_df = pd.DataFrame(rows)
    st.table(comp_df)
else:
    st.info("Model metrics not found. Run the evaluation script first.")

st.caption("*All charts are interactive – hover for details.*")
